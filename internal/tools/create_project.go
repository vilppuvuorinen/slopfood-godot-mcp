package tools

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"

	"github.com/vilppuvuorinen/slopfood-godot-mcp/internal/godot"
	"github.com/vilppuvuorinen/slopfood-godot-mcp/internal/mcp"
)

const (
	// godot4ConfigVersion is the config_version Godot 4.x writes to project.godot.
	godot4ConfigVersion = 5

	// defaultGodotVersion is the major.minor feature tag used when the engine
	// version cannot be determined; it tracks the pinned engine minor.
	defaultGodotVersion = godot.DefaultMinor

	defaultDotnetTargetFramework = "net8.0"
)

func (t *toolset) createProject() mcp.Tool {
	return mcp.Tool{
		Name:        "create_project",
		Title:       "Create Project",
		Description: "Create a new Godot project in the bound project root (additive; fails if project.godot already exists)",
		Annotations: &mcp.ToolAnnotations{DestructiveHint: mcp.Bool(false), IdempotentHint: mcp.Bool(false), OpenWorldHint: mcp.Bool(false)},
		InputSchema: map[string]any{
			"type": "object",
			"properties": map[string]any{
				"projectName": map[string]any{
					"type":        "string",
					"description": "Name of the project",
				},
				"description": map[string]any{
					"type":        "string",
					"description": "Optional project description (config/description)",
				},
				"mainScene": map[string]any{
					"type":        "string",
					"description": "Optional main scene (run/main_scene); a res:// path or a project-relative one",
				},
				"dotnet": map[string]any{
					"type":        "boolean",
					"description": `Scaffold a .NET (C#) project (.csproj + "C#" feature). Default: false`,
				},
			},
			"required": []string{"projectName"},
		},
		OutputSchema: statusOutputSchema(map[string]any{
			"projectPath": map[string]any{"type": "string"},
			"projectName": map[string]any{"type": "string"},
			"dotnet":      map[string]any{"type": "boolean"},
		}),
		Handler: t.handleCreateProject,
	}
}

type createProjectArgs struct {
	ProjectName string `json:"projectName"`
	Description string `json:"description"`
	MainScene   string `json:"mainScene"`
	Dotnet      bool   `json:"dotnet"`
}

func (t *toolset) handleCreateProject(ctx context.Context, raw json.RawMessage) (any, error) {
	args, err := decodeArgs[createProjectArgs](raw)
	if err != nil {
		return nil, err
	}
	project := t.project
	if result, missing := requireFields("projectName", args.ProjectName); missing {
		return result, nil
	}
	if !validPath(project) {
		return invalidPathResult(), nil
	}
	if !validProjectName(args.ProjectName) {
		return mcp.ErrorResult("Invalid project name."), nil
	}
	if hasControlChars(args.Description) {
		return mcp.ErrorResult("Invalid project description."), nil
	}
	if hasControlChars(args.MainScene) {
		return mcp.ErrorResult("Invalid main scene path."), nil
	}
	if args.MainScene != "" && !validPath(args.MainScene) {
		return invalidPathResult(), nil
	}

	projectFile := filepath.Join(project, "project.godot")
	switch _, err := os.Stat(projectFile); {
	case err == nil:
		return mcp.ErrorResult("A project.godot already exists at this path."), nil
	case !errors.Is(err, os.ErrNotExist):
		return nil, fmt.Errorf("stat project file: %w", err)
	}

	if err := os.MkdirAll(project, 0o755); err != nil { //nolint:gosec // the project path is bound at startup.
		return nil, fmt.Errorf("create project directory: %w", err)
	}

	isDotnet := args.Dotnet
	assemblyName := toDotnetIdentifier(args.ProjectName)
	// Derive the feature tag from the installed engine so a 4.7 project does not
	// advertise the stale 4.4 tag the scaffold once hardcoded.
	engineVersion := t.detectEngineVersion(ctx)
	mainScene := ""
	if strings.TrimSpace(args.MainScene) != "" {
		mainScene = toResourcePath(args.MainScene)
	}

	var content strings.Builder
	content.WriteString("; Engine configuration file.\n; Generated by slopfood-godot-mcp.\n\n")
	content.WriteString("config_version=" + strconv.Itoa(godot4ConfigVersion) + "\n\n[application]\n\n")
	content.WriteString("config/name=\"" + escapeGodotString(args.ProjectName) + "\"\n")
	if args.Description != "" {
		content.WriteString("config/description=\"" + escapeGodotString(args.Description) + "\"\n")
	}
	if mainScene != "" {
		content.WriteString("run/main_scene=\"" + escapeGodotString(mainScene) + "\"\n")
	}
	content.WriteString("config/features=" + generateGodotProjectFeatures(isDotnet, engineVersion) + "\n")
	if isDotnet {
		content.WriteString("\n[dotnet]\n\nproject/assembly_name=\"" + escapeGodotString(assemblyName) + "\"\n")
	}
	if err := os.WriteFile(projectFile, []byte(content.String()), 0o644); err != nil { //nolint:gosec // user-facing project file.
		return nil, fmt.Errorf("write project file: %w", err)
	}

	if isDotnet {
		csproj := generateCsprojContent(args.ProjectName, engineVersion+".0", defaultDotnetTargetFramework)
		csprojPath := filepath.Join(project, assemblyName+".csproj")
		if err := os.WriteFile(csprojPath, []byte(csproj), 0o644); err != nil { //nolint:gosec // user-facing project file.
			return nil, fmt.Errorf("write csproj: %w", err)
		}
	}

	message := fmt.Sprintf("Project %q created at %s", args.ProjectName, project)
	if isDotnet {
		message += " (Godot .NET / C#)"
	}
	return statusResult(project, message, map[string]any{
		"projectName": args.ProjectName,
		"dotnet":      isDotnet,
	}), nil
}

// engineVersionPattern captures the major and minor of a Godot version string,
// e.g. "4.7.2.stable.official" yields "4" and "7".
var engineVersionPattern = regexp.MustCompile(`^(\d+)\.(\d+)`)

var dotnetIdentifierChars = regexp.MustCompile(`[^A-Za-z0-9_]`)

// escapeGodotString escapes a value for a double-quoted Godot config string.
// Godot's variant parser understands C-style escapes.
func escapeGodotString(s string) string {
	return strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s)
}

// hasControlChars reports whether s contains characters that would break a
// single-line Godot config value and allow config injection.
func hasControlChars(s string) bool {
	for _, r := range s {
		if r < 0x20 || r == 0x7f {
			return true
		}
	}
	return false
}

// validProjectName rejects control characters that would allow config injection.
func validProjectName(name string) bool {
	return strings.TrimSpace(name) != "" && !hasControlChars(name)
}

// toResourcePath renders a caller-supplied scene path as a res:// path.
func toResourcePath(path string) string {
	path = strings.TrimSpace(path)
	if strings.HasPrefix(path, resScheme) {
		return path
	}
	return resScheme + strings.TrimPrefix(path, "/")
}

func toDotnetIdentifier(name string) string {
	cleaned := dotnetIdentifierChars.ReplaceAllString(name, "_")
	if cleaned == "" {
		return "Game"
	}
	if cleaned[0] >= '0' && cleaned[0] <= '9' {
		return "_" + cleaned
	}
	return cleaned
}

func generateGodotProjectFeatures(isDotnet bool, version string) string {
	if isDotnet {
		return fmt.Sprintf("PackedStringArray(%q, %q)", version, "C#")
	}
	return fmt.Sprintf("PackedStringArray(%q)", version)
}

func generateCsprojContent(projectName, sdkVersion, targetFramework string) string {
	rootNamespace := toDotnetIdentifier(projectName)
	return fmt.Sprintf(`<Project Sdk="Godot.NET.Sdk/%s">
  <PropertyGroup>
    <TargetFramework>%s</TargetFramework>
    <EnableDynamicLoading>true</EnableDynamicLoading>
    <Nullable>enable</Nullable>
    <RootNamespace>%s</RootNamespace>
  </PropertyGroup>
</Project>
`, sdkVersion, targetFramework, rootNamespace)
}

// detectEngineVersion returns the engine's major.minor feature tag, e.g.
// "4.7", derived from the installed engine rather than a hardcoded default.
// When the engine cannot be queried or reports an unparseable version it falls
// back to defaultGodotVersion.
func (t *toolset) detectEngineVersion(ctx context.Context) string {
	if t.engine == nil {
		return defaultGodotVersion
	}
	out, err := t.engine.Version(ctx)
	if err != nil {
		return defaultGodotVersion
	}
	match := engineVersionPattern.FindStringSubmatch(strings.TrimSpace(out))
	if match == nil {
		return defaultGodotVersion
	}
	return match[1] + "." + match[2]
}
