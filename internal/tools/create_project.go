package tools

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"

	"github.com/vilppuvuorinen/go-dot-mcp/internal/godot"
	"github.com/vilppuvuorinen/go-dot-mcp/internal/mcp"
)

const (
	// defaultGodotVersion is written to config/features when the reference
	// server has no version to go on.
	defaultGodotVersion = "4.4"

	defaultGodotNetSDKVersion    = "4.4.0"
	defaultDotnetTargetFramework = "net8.0"
)

// createProjectAliases lets callers use the snake_case spellings too.
var createProjectAliases = map[string]string{
	"project_path": "projectPath",
	"project_name": "projectName",
}

func createProject() mcp.Tool {
	return mcp.Tool{
		Name:        "create_project",
		Title:       "Create Project",
		Description: "Create a new Godot project from scratch",
		Annotations: &mcp.ToolAnnotations{DestructiveHint: mcp.Bool(false), OpenWorldHint: mcp.Bool(false)},
		InputSchema: map[string]any{
			"type": "object",
			"properties": map[string]any{
				"projectPath": map[string]any{
					"type":        "string",
					"description": "Directory where the project will be created",
				},
				"projectName": map[string]any{
					"type":        "string",
					"description": "Name of the project",
				},
				"dotnet": map[string]any{
					"type":        "boolean",
					"description": `Scaffold a .NET (C#) project (.csproj + "C#" feature). Default: false`,
				},
			},
			"required": []string{"projectPath", "projectName"},
		},
		Handler: handleCreateProject,
	}
}

type createProjectArgs struct {
	ProjectPath string `json:"projectPath"`
	ProjectName string `json:"projectName"`
	Dotnet      bool   `json:"dotnet"`
}

func handleCreateProject(ctx context.Context, raw json.RawMessage) (any, error) {
	raw, err := aliasParams(raw, createProjectAliases)
	if err != nil {
		return nil, err
	}
	var args createProjectArgs
	if len(raw) > 0 && string(raw) != "null" {
		if err := json.Unmarshal(raw, &args); err != nil {
			return nil, fmt.Errorf("invalid arguments: %w", err)
		}
	}
	if args.ProjectPath == "" || args.ProjectName == "" {
		return mcp.ErrorResult("projectPath and projectName are required."), nil
	}
	if !validPath(args.ProjectPath) {
		return mcp.ErrorResult("Invalid path."), nil
	}
	if !validProjectName(args.ProjectName) {
		return mcp.ErrorResult("Invalid project name."), nil
	}

	projectFile := filepath.Join(args.ProjectPath, "project.godot")
	switch _, err := os.Stat(projectFile); {
	case err == nil:
		return mcp.ErrorResult("A project.godot already exists at this path."), nil
	case !errors.Is(err, os.ErrNotExist):
		return nil, fmt.Errorf("stat project file: %w", err)
	}

	if err := os.MkdirAll(args.ProjectPath, 0o755); err != nil { //nolint:gosec // projectPath is caller-controlled.
		return nil, fmt.Errorf("create project directory: %w", err)
	}

	isDotnet := args.Dotnet
	assemblyName := toDotnetIdentifier(args.ProjectName)
	content := "; Engine configuration file.\n; Generated by Godot MCP.\n\nconfig_version=" + strconv.Itoa(godot4ConfigVersion) + "\n\n[application]\n\n" +
		"config/name=\"" + escapeGodotString(args.ProjectName) + "\"\n" +
		"config/features=" + generateGodotProjectFeatures(isDotnet, defaultGodotVersion) + "\n"
	if isDotnet {
		content += "\n[dotnet]\n\nproject/assembly_name=\"" + escapeGodotString(assemblyName) + "\"\n"
	}
	if err := os.WriteFile(projectFile, []byte(content), 0o644); err != nil { //nolint:gosec // user-facing project file.
		return nil, fmt.Errorf("write project file: %w", err)
	}

	if isDotnet {
		sdkVersion := detectGodotNetSDKVersion(ctx)
		csproj := generateCsprojContent(args.ProjectName, sdkVersion, defaultDotnetTargetFramework)
		csprojPath := filepath.Join(args.ProjectPath, assemblyName+".csproj")
		if err := os.WriteFile(csprojPath, []byte(csproj), 0o644); err != nil { //nolint:gosec // user-facing project file.
			return nil, fmt.Errorf("write csproj: %w", err)
		}
	}

	message := fmt.Sprintf("Project %q created at %s", args.ProjectName, args.ProjectPath)
	if isDotnet {
		message += " (Godot .NET / C#)"
	}
	return mcp.TextResult(message), nil
}

var (
	dotnetIdentifierChars = regexp.MustCompile(`[^A-Za-z0-9_]`)
	godotStableVersion    = regexp.MustCompile(`^(\d+)\.(\d+)(?:\.\d+)?\.stable\b`)
)

// escapeGodotString escapes a value for embedding in a double-quoted Godot
// config string. Godot's variant parser understands C-style escapes, so
// backslashes and double quotes are enough to keep the value on one line.
func escapeGodotString(s string) string {
	return strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s)
}

// validProjectName reports whether a project name is safe to write into
// project.godot. Names must be non-blank and free of control characters
// (including newlines and NUL), which have no place in a single-line config
// entry and would otherwise allow injection.
func validProjectName(name string) bool {
	if strings.TrimSpace(name) == "" {
		return false
	}
	for _, r := range name {
		if r < 0x20 || r == 0x7f {
			return false
		}
	}
	return true
}

// toDotnetIdentifier turns an arbitrary project name into a valid C#/.NET
// identifier, replacing invalid characters and escaping a leading digit.
func toDotnetIdentifier(name string) string {
	cleaned := dotnetIdentifierChars.ReplaceAllString(name, "_")
	if cleaned == "" {
		return "Game"
	}
	if cleaned[0] >= '0' && cleaned[0] <= '9' {
		return "_" + cleaned
	}
	return cleaned
}

// generateGodotProjectFeatures builds the config/features value written to
// project.godot, adding the "C#" feature for .NET projects.
func generateGodotProjectFeatures(isDotnet bool, version string) string {
	if isDotnet {
		return fmt.Sprintf("PackedStringArray(%q, %q)", version, "C#")
	}
	return fmt.Sprintf("PackedStringArray(%q)", version)
}

// generateCsprojContent builds a minimal Godot .NET SDK project file.
func generateCsprojContent(projectName, sdkVersion, targetFramework string) string {
	rootNamespace := toDotnetIdentifier(projectName)
	return fmt.Sprintf(`<Project Sdk="Godot.NET.Sdk/%s">
  <PropertyGroup>
    <TargetFramework>%s</TargetFramework>
    <EnableDynamicLoading>true</EnableDynamicLoading>
    <Nullable>enable</Nullable>
    <RootNamespace>%s</RootNamespace>
  </PropertyGroup>
</Project>
`, sdkVersion, targetFramework, rootNamespace)
}

// detectGodotNetSDKVersion matches the installed Godot's major.minor to a
// Godot.NET.Sdk version, falling back to the reference default when Godot is
// unavailable or reports a non-stable build.
func detectGodotNetSDKVersion(ctx context.Context) string {
	out, err := godot.Version(ctx, godot.Path())
	if err != nil {
		return defaultGodotNetSDKVersion
	}
	match := godotStableVersion.FindStringSubmatch(strings.TrimSpace(out))
	if match == nil {
		return defaultGodotNetSDKVersion
	}
	return match[1] + "." + match[2] + ".0"
}
